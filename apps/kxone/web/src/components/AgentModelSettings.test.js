import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import AgentModelSettings from './AgentModelSettings.vue'
import { agentAPI } from '@/api/agent'
vi.mock('@/api/agent', () => ({ agentAPI: { settings: vi.fn(), saveSettings: vi.fn(), testSettings: vi.fn() } }))
const existing = { base_url: 'https://provider.example/v1', model: 'example-model', key_configured: true, enabled: true, budget_micro: 300e6, version: 4 }
beforeEach(() => { vi.clearAllMocks(); agentAPI.settings.mockResolvedValue(existing); agentAPI.saveSettings.mockResolvedValue(existing); agentAPI.testSettings.mockResolvedValue({ ok: true, model: existing.model, latency_ms: 123 }) })
describe('web model configuration', () => {
  it('states the configured-price estimate and retains unknown-usage reservations', async () => {
    agentAPI.settings.mockResolvedValue({ ...existing, spent_micro: 1250000, reserved_micro: 500000 })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    expect(wrapper.text()).toContain('本月按配置单价估算 ¥1.25')
    expect(wrapper.text()).toContain('预留 ¥0.50')
    expect(wrapper.text()).toContain('用量未知的调用继续占用预留')
    expect(wrapper.text()).toContain('最终费用需与服务商账单核对')
    wrapper.unmount()
  })
  it('labels retained-conversation health and keeps missing samples distinct from zero', async () => {
    agentAPI.settings.mockResolvedValue({ ...existing, run_health: { month: '2026-10', scope: '本月保留会话中的分析任务，删除会话后不再计入', total: 2, completed: 0, failed: 0, interrupted: 0, cancelled: 1, budget_exceeded: 0, queued: 0, running: 1, failure_rate: null, failure_sample_count: 0, average_duration_ms: null, duration_sample_count: 0, unknown_duration_count: 0 } })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    const health = wrapper.find('[aria-label="分析运行情况"]')
    expect(health.text()).toContain('删除会话后不再计入')
    expect(health.text()).toContain('失败率：—')
    expect(health.text()).toContain('成功分析平均耗时：—')
    expect(health.text()).toContain('已取消 1')
    expect(health.text()).toContain('运行中 1')
    wrapper.unmount()
  })
  it('renders valid health metrics with denominator and duration coverage', async () => {
    agentAPI.settings.mockResolvedValue({ ...existing, run_health: { month: '2026-10', scope: '本月保留会话中的分析任务，删除会话后不再计入', total: 7, completed: 3, failed: 1, interrupted: 1, cancelled: 1, budget_exceeded: 1, queued: 0, running: 0, failure_rate: 0.4, failure_sample_count: 5, average_duration_ms: 1250, duration_sample_count: 2, unknown_duration_count: 1 } })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    const health = wrapper.find('[aria-label="分析运行情况"]')
    expect(health.text()).toContain('失败率：40.0%')
    expect(health.text()).toContain('统计 5 项')
    expect(health.text()).toContain('成功分析平均耗时：1.25 秒')
    expect(health.text()).toContain('可信时间 2 项')
    expect(health.text()).toContain('缺少可信耗时 1 项')
    expect(health.text()).toContain('额度不足 1')
    wrapper.unmount()
  })
  it('does not invent operation health for a response without administrator metrics', async () => {
    const wrapper = mount(AgentModelSettings); await flushPromises()
    expect(wrapper.find('[aria-label="分析运行情况"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('leaves a new service URL empty and uses a clearly illustrative business-space placeholder', async () => {
    agentAPI.settings.mockResolvedValue({ ...existing, base_url: '', key_configured: false })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    expect(wrapper.find('input[name="ai-base-url"]').element.value).toBe('')
    expect(wrapper.find('input[name="ai-base-url"]').attributes('placeholder')).toContain('llm-xxx.cn-beijing.maas.aliyuncs.com')
    expect(agentAPI.testSettings).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('saves versioned config, keeps a blank key unchanged and clears a new key after success', async () => {
    const wrapper = mount(AgentModelSettings); await flushPromises()
    await wrapper.find('input[name="ai-api-key"]').setValue('test-secret-value')
    await wrapper.find('form').trigger('submit'); await flushPromises()
    expect(agentAPI.saveSettings).toHaveBeenCalledWith(expect.objectContaining({ api_key: 'test-secret-value', expected_version: 4, budget_micro: 300e6 }))
    expect(wrapper.find('input[name="ai-api-key"]').element.value).toBe('')
    wrapper.unmount()
  })
  it('preserves entered config after a conflict and tests only on explicit click', async () => {
    agentAPI.saveSettings.mockRejectedValue({ response: { status: 409 } })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    await wrapper.find('input[name="ai-model"]').setValue('new-model')
    await wrapper.find('input[name="ai-api-key"]').setValue('private-secret')
    expect(agentAPI.testSettings).not.toHaveBeenCalled()
    await wrapper.find('form').trigger('submit'); await flushPromises()
    expect(wrapper.find('[role="alert"]').text()).toContain('当前输入已保留')
    expect(wrapper.find('input[name="ai-model"]').element.value).toBe('new-model')
    expect(wrapper.find('input[name="ai-api-key"]').element.value).toBe('private-secret')
    await wrapper.findAll('button').find(button => button.text() === '测试连接').trigger('click'); await flushPromises()
    expect(agentAPI.testSettings).toHaveBeenCalledWith({ base_url: existing.base_url, api_key: 'private-secret', model: 'new-model', input_price_cny: 12, output_price_cny: 36 })
    expect(wrapper.text()).toContain('连接成功')
    wrapper.unmount()
  })
  it('saves the backup draft through the versioned endpoint and clears its key input', async () => {
    agentAPI.settings.mockResolvedValue({ ...existing, fallback: { enabled: true, base_url: 'https://api.deepseek.com', model: 'deepseek-flash', key_configured: true, input_price_cny: 2, output_price_cny: 8 } })
    const wrapper = mount(AgentModelSettings); await flushPromises()
    expect(wrapper.find('input[name="ai-fallback-key"]').element.value).toBe('')
    await wrapper.find('input[name="ai-fallback-key"]').setValue('synthetic-backup-credential')
    await wrapper.find('form').trigger('submit'); await flushPromises()
    expect(agentAPI.saveSettings).toHaveBeenCalledWith(expect.objectContaining({ expected_version: 4, fallback: expect.objectContaining({ enabled: true, model: 'deepseek-flash', api_key: 'synthetic-backup-credential', input_price_cny: 2, output_price_cny: 8 }) }))
    expect(wrapper.find('input[name="ai-fallback-key"]').element.value).toBe('')
    wrapper.unmount()
  })
  it('tests the backup only on explicit click and keeps draft input after conflict', async () => {
    const wrapper = mount(AgentModelSettings); await flushPromises()
    await wrapper.find('input[name="ai-fallback-url"]').setValue('https://api.deepseek.com')
    await wrapper.find('input[name="ai-fallback-key"]').setValue('synthetic-backup-credential')
    expect(agentAPI.testSettings).not.toHaveBeenCalled()
    await wrapper.findAll('button').find(button => button.text() === '测试备用连接').trigger('click'); await flushPromises()
    expect(agentAPI.testSettings).toHaveBeenCalledWith({ target: 'fallback', fallback: expect.objectContaining({ api_key: 'synthetic-backup-credential', model: 'deepseek-flash' }) })
    agentAPI.saveSettings.mockRejectedValue({ response: { status: 409 } })
    await wrapper.find('form').trigger('submit'); await flushPromises()
    expect(wrapper.find('input[name="ai-fallback-key"]').element.value).toBe('synthetic-backup-credential')
    expect(wrapper.find('[role="alert"]').text()).toContain('当前输入已保留')
    wrapper.unmount()
  })

})
