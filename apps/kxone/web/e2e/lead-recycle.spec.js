import { randomUUID } from 'node:crypto'
import { test, expect } from '@playwright/test'

for (const width of [375, 1440]) {
  test(`admin deletion and restore preserve the lead; other roles cannot delete ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.request.get('/test-session')
    const created = await page.request.post('/api/leads', { headers: { 'Idempotency-Key': randomUUID() }, data: { customer_name: `隔离回收测试${width}`, customer_mobile: '13912345678', city: '襄阳', source_channel: '主动来电（员工丙）' } })
    expect(created.ok(), await created.text()).toBeTruthy()
    const { lead } = await created.json()
    await page.goto(`/leads/${lead.id}`)
    if (width < 768) await page.getByRole('button', { name: '更多线索操作' }).click()
    else if (await page.locator('.more-actions-toggle').count()) await page.locator('.more-actions-toggle').click()
    await expect(page.getByRole('button', { name: '删除线索', exact: true })).toHaveCount(0)
    const forbidden = await page.request.delete(`/api/leads/${lead.id}`, { data: { lead_no: lead.lead_no, reason: '权限校验', version: lead.version, profile_version: lead.profile_version } })
    expect(forbidden.status()).toBe(403)
    await page.request.get('/test-session?user=admin')
    await page.goto(`/leads/${lead.id}`)
    if (width < 768) await page.getByRole('button', { name: '更多线索操作' }).click()
    else if (await page.locator('.more-actions-toggle').count()) await page.locator('.more-actions-toggle').click()
    await page.getByRole('button', { name: '删除线索', exact: true }).click()
    const dialog = page.locator('.delete-lead-popup')
    await dialog.getByLabel('确认编号', { exact: true }).fill(lead.lead_no)
    await dialog.getByLabel('删除原因', { exact: true }).fill('隔离数据库中的视觉与业务回归')
    await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(page).toHaveURL(/\/leads(?:\?.*)?$/)
    expect((await page.request.get(`/api/leads/${lead.id}`)).status()).toBe(404)
    await page.goto('/admin/settings?section=recycle')
    const row = page.locator('.recycle-item').filter({ hasText: lead.lead_no })
    await expect(row).toContainText('隔离数据库中的视觉与业务回归')
    await row.getByRole('button', { name: '恢复线索', exact: true }).click()
    await page.getByRole('dialog', { name: '恢复线索', exact: true }).getByRole('button', { name: '取消', exact: true }).click()
    await expect(row).toBeVisible()
    await row.getByRole('button', { name: '恢复线索', exact: true }).click()
    await page.getByRole('button', { name: '确认恢复', exact: true }).click()
    await expect(row).toHaveCount(0)
    const restored = await page.request.get(`/api/leads/${lead.id}`)
    expect(restored.ok(), await restored.text()).toBeTruthy()
    expect((await restored.json()).lead.lead_no).toBe(lead.lead_no)
  })
}
