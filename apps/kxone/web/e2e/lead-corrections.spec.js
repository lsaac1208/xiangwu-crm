    expect(detail.lead.dispatch_manager_userid).toBe('manager_002')
    expect(detail.lead.assigned_inviter_userid).toBe('manager_002')
    // A fresh browser navigation loads the recipient's actual session and role.
    await page.request.get('/test-session?user=manager_002')
    await page.goto(`/leads/${lead.id}`)
    await page.getByRole('button', { name: '立即认领', exact: true }).click()
    await page.getByRole('button', { name: '确认', exact: true }).click()
