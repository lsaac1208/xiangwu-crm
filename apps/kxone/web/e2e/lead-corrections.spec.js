    await page.getByText(lead.customer_name, { exact: true }).first().click()
    await expect(page).toHaveURL(/\/leads\/\d+\?return_to=/)
    await page.reload()
    await page.getByRole('button', { name: '返回', exact: true }).click()
    expect(new URL(page.url()).searchParams.get('keyword')).toBe(lead.customer_name)
    expect(new URL(page.url()).searchParams.get('owner')).toBe('manager_001')
    expect(new URL(page.url()).searchParams.get('sort_by')).toBe('created_at')
    await expect(page.getByText(lead.customer_name, { exact: true }).first()).toBeVisible()
    await page.getByText(lead.customer_name, { exact: true }).first().click()
    await openAction(page, width, '标记成交')
