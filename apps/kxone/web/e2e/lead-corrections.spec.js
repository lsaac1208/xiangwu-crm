import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

async function createLead(page, suffix, invalid = false) {
  await page.request.get('/test-session')
  const response = await page.request.post('/api/leads', { headers: { 'Idempotency-Key': randomUUID() }, data: {
    customer_name: `回归客户${suffix}`, customer_mobile: '13912345678', city: '襄阳', product_name: '高三文化课全日制冲刺班及复读提分长期咨询项目', source_channel: '主动来电（员工丙）'
  } })
  expect(response.ok(), await response.text()).toBeTruthy()
  const { lead } = await response.json()
  const claim = await page.request.post(`/api/leads/${lead.id}/assign`, { data: { sales_userid: 'manager_001' } })
  expect(claim.ok(), await claim.text()).toBeTruthy()
  const claimed = await page.request.post(`/api/leads/${lead.id}/claim`)
  expect(claimed.ok(), await claimed.text()).toBeTruthy()
  if (invalid) {
    const result = await page.request.post(`/api/leads/${lead.id}/followups`, { headers: { 'Idempotency-Key': randomUUID() }, data: { followup_result: 'connected', is_valid: false, invalid_reason: 'wrong_number', remark: '原始无效记录' } })
    expect(result.ok(), await result.text()).toBeTruthy()
  }
  return lead
}

async function openAction(page, width, name) {
  if (width < 768) await page.getByRole('button', { name: '更多线索操作' }).click()
  await page.getByRole('button', { name, exact: true }).click()
}

async function noOverflow(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
}

