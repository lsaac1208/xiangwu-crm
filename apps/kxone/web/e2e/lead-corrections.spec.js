test('失败保留表单、版本冲突、键盘焦点', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const lead = await createLead(page, '冲突')
  await page.request.post(`/api/leads/${lead.id}/convert`, { data: { deal_amount: 1000, payment_status: 'partial' } })
  await page.goto(`/leads/${lead.id}`)
  await openAction(page, 1440, '编辑成交信息')
  const dialog = page.getByRole('dialog', { name: '编辑成交信息' })
  await dialog.getByLabel('累计收款金额').fill('2000')
  await dialog.getByLabel('修改原因').fill('金额纠错')
  const { lead: latest } = await (await page.request.get(`/api/leads/${lead.id}`)).json()
  const changed = await page.request.patch(`/api/leads/${lead.id}/deal`, { data: { expected_version: latest.version, reason: '另一个窗口修改', payment_status: 'paid', deal_amount: 3000 } })
  expect(changed.ok()).toBeTruthy()
  await dialog.getByRole('button', { name: '保存修改' }).click()
  await expect(dialog.getByRole('alert')).toContainText('线索已被他人修改')
  await expect(dialog.getByLabel('累计收款金额')).toHaveValue('2000')
  await dialog.getByRole('button', { name: '保存修改' }).focus()
  await page.keyboard.press('Tab')
  expect(await dialog.evaluate(el => el.contains(document.activeElement))).toBeTruthy()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: '编辑成交信息', exact: true })).toBeFocused()
  expect((await (await page.request.get(`/api/leads/${lead.id}`)).json()).lead.deal_amount).toBe(3000)
})

test('真实录入与跟进提交后正常返回，退出清除会话', async ({ page }) => {
  await page.request.get('/test-session')
  await page.goto('/leads/new')
  await page.getByLabel('客户姓名', { exact: true }).fill('界面验收家长')
  await page.getByRole('button', { name: '创建线索并查看详情' }).click()
  await expect(page.getByText('联系电话与微信号至少填写一项', { exact: true })).toBeVisible()
  await page.getByLabel('微信号', { exact: true }).fill('ui-test-parent')
  await page.getByLabel('来源渠道', { exact: true }).selectOption('主动来电（员工丙）')
  await page.getByRole('button', { name: '创建线索并查看详情' }).click()
  await expect(page).toHaveURL(/\/leads\/\d+$/)
  const leadId = new URL(page.url()).pathname.split('/').pop()
  const assign = await page.request.post(`/api/leads/${leadId}/assign`, { data: { sales_userid: 'manager_001' } })
  expect(assign.ok(), await assign.text()).toBeTruthy()
  const claim = await page.request.post(`/api/leads/${leadId}/claim`)
  expect(claim.ok(), await claim.text()).toBeTruthy()
  // Direct entry has no detail page in SPA history; submitting must still go to this lead.
  await page.goto(`/leads/${leadId}/followup?return_to=%2Fleads%3Fstatus%3Dall`)
  await page.getByLabel('跟进内容', { exact: true }).fill('浏览器实际提交：已联系家长并介绍课程。')
  await page.getByRole('button', { name: '提交邀约跟进' }).click()
  await expect(page).toHaveURL(new RegExp(`/leads/${leadId}\\?return_to=`))
  await expect(page.getByText('浏览器实际提交：已联系家长并介绍课程。', { exact: true })).toBeVisible()
  const detail = await (await page.request.get(`/api/leads/${leadId}`)).json()
  expect(detail.followups).toHaveLength(1)
  await page.getByRole('button', { name: '当前账户', exact: true }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await page.getByRole('button', { name: '确认', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  const cookies = await page.context().cookies()
  expect(cookies.some(cookie => cookie.name === 'kxone_access_token')).toBeFalsy()
  expect((await page.request.get('/api/user/info')).status()).toBe(401)
})
